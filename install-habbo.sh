#!/usr/bin/env bash
#
# Habbo Launcher for Linux — UNOFFICIAL installer
#
# Not affiliated with, endorsed by, or supported by Sulake or Habbo.
# This script contains no Habbo software. It downloads the official
# Windows launcher from Habbo's own servers (or uses one you downloaded)
# and sets it up to run under Wine, with an app-menu entry and a
# handler so the "Launch and log in" button on habbo.com works.
#
# Help: https://github.com/Sentinaut/Habbo-Linux/issues  (or Sentinaut on Discord)
#
# Usage:
#   ./install-habbo.sh                      install (or repair/update)
#   ./install-habbo.sh --installer FILE     use a HabboLauncher-Setup .exe you downloaded
#   ./install-habbo.sh --no-gpu             disable GPU acceleration (if the launcher crashes)
#   ./install-habbo.sh --dxvk               also install DXVK (smoother graphics, needs winetricks + Vulkan)
#   ./install-habbo.sh --uninstall          remove everything this script created
#
# Environment overrides:
#   WINE=/path/to/wine          Wine binary to use (default: wine on your PATH)
#   HABBO_PREFIX=/some/dir      where to keep the Wine prefix
#   HABBO_INSTALLER_URL=URL     where to download the installer from

set -euo pipefail

# ---------------------------------------------------------------- settings ---

APP_ID="habbo-launcher"
APP_NAME="Habbo Launcher"
MARKER="Generated by the unofficial Habbo Launcher installer"
HELP_URL="https://github.com/Sentinaut/Habbo-Linux/issues"
HELP_TEXT="Need help? Open an issue at $HELP_URL or message Sentinaut on Discord."

DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}"
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}"
APP_DIR="$DATA_DIR/$APP_ID"
PREFIX_DIR="${HABBO_PREFIX:-$APP_DIR/prefix}"
BIN_DIR="$HOME/.local/bin"
WRAPPER="$BIN_DIR/$APP_ID"
DESKTOP_DIR="$DATA_DIR/applications"
DESKTOP_FILE="$DESKTOP_DIR/$APP_ID.desktop"
ICON_FILE="$DATA_DIR/icons/$APP_ID.png"
LOG_FILE="$CACHE_DIR/$APP_ID.log"

# The launcher updates itself on first run, so an older installer is fine.
INSTALLER_URL="${HABBO_INSTALLER_URL:-https://images.habbo.com/habbo-native-clients/launcher/HabboLauncher-Setup-1.0.80.exe}"

# Wine 7.x was observed to crash this launcher; 8+ is known to work better.
MIN_WINE_MAJOR=8
WINE="${WINE:-wine}"
WINESERVER="${WINESERVER:-wineserver}"

LOCAL_INSTALLER=""
FORCE_OLD_WINE=0
NO_GPU=0
WANT_DXVK=0
DO_UNINSTALL=0

# ----------------------------------------------------------------- helpers ---

if [[ -t 1 ]]; then
  C_INFO=$'\e[1;34m'; C_OK=$'\e[1;32m'; C_WARN=$'\e[1;33m'; C_ERR=$'\e[1;31m'; C_OFF=$'\e[0m'
else
  C_INFO=""; C_OK=""; C_WARN=""; C_ERR=""; C_OFF=""
fi
info() { printf '%s==>%s %s\n' "$C_INFO" "$C_OFF" "$*"; }
ok()   { printf '%s==>%s %s\n' "$C_OK" "$C_OFF" "$*"; }
warn() { printf '%sWarning:%s %s\n' "$C_WARN" "$C_OFF" "$*" >&2; }
die()  { printf '%sError:%s %s\n\n%s\n' "$C_ERR" "$C_OFF" "$*" "$HELP_TEXT" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

usage() { awk 'NR > 2 && /^#/ { sub(/^# ?/, ""); print; next } NR > 2 { exit }' "$0"; }

wait_wine() {
  if have "$WINESERVER"; then
    WINEPREFIX="$PREFIX_DIR" "$WINESERVER" -w 2>/dev/null || true
  else
    sleep 5
  fi
}

print_wine_hint() {
  local ids=""
  if [[ -r /etc/os-release ]]; then
    ids="$( . /etc/os-release; echo "${ID:-} ${ID_LIKE:-}" )"
  fi
  echo
  echo "How to get a recent Wine:"
  case "$ids" in
    *arch*|*manjaro*|*endeavouros*)
      echo "  sudo pacman -S wine" ;;
    *fedora*|*rhel*|*centos*|*nobara*)
      echo "  sudo dnf install wine" ;;
    *suse*)
      echo "  sudo zypper install wine" ;;
    *ubuntu*|*debian*|*mint*|*pop*|*elementary*|*zorin*)
      echo "  Your distro's own wine package is often too old."
      echo "  Install winehq-stable from WineHQ's repository instead:"
      echo "  https://gitlab.winehq.org/wine/wine/-/wikis/Download" ;;
    *)
      echo "  https://gitlab.winehq.org/wine/wine/-/wikis/Download" ;;
  esac
  echo
  echo "Note: the Flatpak version of Wine is not supported by this script."
}

# ------------------------------------------------------------------- steps ---

check_system() {
  [[ "${EUID:-$(id -u)}" -ne 0 ]] || die "Don't run this as root or with sudo. Run it as your normal user."
  case "$(uname -m)" in
    x86_64|amd64) ;;
    *) warn "This has only been tested on x86_64 PCs. Your machine is $(uname -m); it may not work." ;;
  esac
  if ! have curl && ! have wget && [[ -z "$LOCAL_INSTALLER" ]]; then
    die "Need curl or wget to download the installer (or pass --installer FILE)."
  fi
}

check_wine() {
  if ! have "$WINE"; then
    printf '%sError:%s Wine is not installed.\n' "$C_ERR" "$C_OFF" >&2
    print_wine_hint
    exit 1
  fi
  WINE="$(command -v "$WINE")"

  local ver major
  ver="$("$WINE" --version 2>/dev/null || true)"
  major="$(sed -nE 's/^wine-([0-9]+).*/\1/p' <<<"$ver")"

  if [[ -z "$major" ]]; then
    warn "Couldn't read the Wine version ('$ver'). Carrying on anyway."
  elif (( major < MIN_WINE_MAJOR )); then
    if (( FORCE_OLD_WINE )); then
      warn "$ver is older than recommended (wine-$MIN_WINE_MAJOR or later). Continuing because of --force-old-wine."
    else
      printf '%sError:%s %s is too old; Habbo Launcher needs wine-%s or later.\n' \
        "$C_ERR" "$C_OFF" "$ver" "$MIN_WINE_MAJOR" >&2
      print_wine_hint
      echo "(To try anyway, re-run with --force-old-wine.)"
      echo; echo "$HELP_TEXT"
      exit 1
    fi
  else
    info "Using $ver"
  fi
}

make_prefix() {
  export WINEPREFIX="$PREFIX_DIR"
  export WINEDEBUG=-all
  # Stop Wine from creating its own menu entries and habbo:// link handlers.
  # Those launch the app without the fixes below and make it crash.
  export WINEDLLOVERRIDES="winemenubuilder.exe=d"
  mkdir -p "$(dirname "$PREFIX_DIR")"

  if [[ -f "$PREFIX_DIR/system.reg" ]]; then
    info "Updating existing Wine prefix at $PREFIX_DIR"
  else
    info "Creating Wine prefix at $PREFIX_DIR (first time can take a minute)..."
  fi
  # Skip the Mono/Gecko install prompts; the launcher doesn't need them.
  WINEDLLOVERRIDES="mscoree,mshtml=;winemenubuilder.exe=d" "$WINE" wineboot -u >/dev/null 2>&1 || true
  wait_wine

  [[ -f "$PREFIX_DIR/system.reg" ]] || die "Wine couldn't create the prefix at $PREFIX_DIR."

  info "Setting the prefix to Windows 10..."
  if ! "$WINE" winecfg -v win10 >/dev/null 2>&1; then
    "$WINE" reg add 'HKCU\Software\Wine' /v Version /d win10 /f >/dev/null 2>&1 \
      || warn "Couldn't set Windows 10 mode; the launcher may crash on start."
  fi
  wait_wine
}

download_failed() {
  rm -f "${INSTALLER:-}"
  die "Couldn't download the installer from:
  $INSTALLER_URL

Download it yourself instead: log in at habbo.com, choose 'Download for Windows',
then run:
  $0 --installer ~/Downloads/HabboLauncher-Setup-<version>.exe"
}

get_installer() {
  if [[ -n "$LOCAL_INSTALLER" ]]; then
    [[ -f "$LOCAL_INSTALLER" ]] || die "Installer not found: $LOCAL_INSTALLER"
    INSTALLER="$LOCAL_INSTALLER"
  else
    INSTALLER="$TMP_DIR/HabboLauncher-Setup.exe"
    info "Downloading the official installer from Habbo..."
    if have curl; then
      curl -fL --retry 3 --progress-bar -o "$INSTALLER" "$INSTALLER_URL" || download_failed
    else
      wget -q --show-progress -O "$INSTALLER" "$INSTALLER_URL" || download_failed
    fi
  fi
  # Every Windows .exe starts with "MZ"; anything else is an error page.
  [[ "$(head -c 2 "$INSTALLER" 2>/dev/null)" == "MZ" ]] \
    || { [[ -n "$LOCAL_INSTALLER" ]] && die "$INSTALLER isn't a Windows installer."; download_failed; }
}

find_exe() {
  find "$PREFIX_DIR/drive_c/users" \
    -path '*/AppData/Local/Programs/habbo-electron-launcher/Habbo Launcher.exe' \
    -print -quit 2>/dev/null || true
}

run_installer() {
  info "Installing Habbo Launcher into the prefix..."
  # NSIS installer: /S = silent, per-user install.
  "$WINE" "$INSTALLER" /S >/dev/null 2>&1 || true
  wait_wine

  EXE="$(find_exe)"
  [[ -n "$EXE" ]] || die "The installer finished but Habbo Launcher.exe wasn't found in the prefix.
Try running it by hand to see what happens:
  WINEPREFIX=\"$PREFIX_DIR\" $WINE \"$INSTALLER\""
  ok "Installed: $EXE"
}

install_dxvk() {
  (( WANT_DXVK )) || return 0
  if ! have winetricks; then
    warn "--dxvk needs winetricks, which isn't installed. Skipping DXVK."
    return 0
  fi
  info "Installing DXVK (this downloads it from GitHub)..."
  if WINEPREFIX="$PREFIX_DIR" winetricks -q dxvk >/dev/null 2>&1; then
    ok "DXVK installed."
  else
    warn "DXVK install failed. Habbo will still work, just with Wine's default graphics."
  fi
  wait_wine
}

detect_scheme() {
  # Find the link scheme the launcher registered (expected: habbo://).
  local reg found=""
  for reg in "$PREFIX_DIR/user.reg" "$PREFIX_DIR/system.reg"; do
    [[ -f "$reg" ]] || continue
    found+="$(awk '/^\[/ { s = $0; next } /^"URL Protocol"=/ { print s }' "$reg" \
      | sed -nE 's/^\[Software\\\\Classes\\\\([^]\\ ]+)\].*/\1/Ip')"$'\n'
  done
  SCHEME="$(grep -i habbo <<<"$found" | head -n 1 | tr '[:upper:]' '[:lower:]' || true)"
  [[ -n "$SCHEME" ]] || SCHEME="habbo"
}

extract_icon() {
  ICON_VALUE="applications-games"
  if ! have wrestool || ! have icotool; then
    info "Tip: install 'icoutils' and re-run to get the real Habbo icon in your menu."
    return 0
  fi
  local d="$TMP_DIR/icon" best=""
  mkdir -p "$d"
  wrestool -x -t 14 -o "$d/" "$EXE" >/dev/null 2>&1 || true
  for ico in "$d"/*.ico; do
    [[ -f "$ico" ]] && icotool -x -o "$d/" "$ico" >/dev/null 2>&1 || true
  done
  best="$(find "$d" -name '*.png' -printf '%s %p\n' 2>/dev/null | sort -n | tail -n 1 | cut -d' ' -f2- || true)"
  if [[ -n "$best" ]]; then
    mkdir -p "$(dirname "$ICON_FILE")"
    cp "$best" "$ICON_FILE"
    ICON_VALUE="$ICON_FILE"
  fi
}

write_wrapper() {
  local gpu_flag="" q_prefix q_wine q_exe q_log
  (( NO_GPU )) && gpu_flag=" --disable-gpu"
  printf -v q_prefix '%q' "$PREFIX_DIR"
  printf -v q_wine '%q' "$WINE"
  printf -v q_exe '%q' "$EXE"
  printf -v q_log '%q' "$LOG_FILE"

  mkdir -p "$BIN_DIR"
  cat >"$WRAPPER" <<EOF
#!/usr/bin/env bash
# $MARKER.
# Re-run install-habbo.sh to regenerate this file.
export WINEPREFIX=$q_prefix
export WINEDEBUG=-all
export WINEDLLOVERRIDES="winemenubuilder.exe=d"
WINE=$q_wine
EXE=$q_exe
FLAGS=(--no-sandbox$gpu_flag)
LOG=$q_log
# Extra seconds to wait after the launcher reports it has started, before
# handing it the login link (its login screen needs a moment to appear).
EXTRA_WAIT="\${HABBO_LINK_DELAY:-0}"
mkdir -p "\$(dirname "\$LOG")"

# Output must go to a file: when started from the app menu or a browser
# there is no terminal, and Electron under Wine crashes trying to write to one.
if [[ \$# -eq 0 ]]; then
  exec "\$WINE" "\$EXE" "\${FLAGS[@]}" >"\$LOG" 2>&1
fi

# Opened from a habbo:// link. A running launcher accepts the link, but one
# that is just starting up ignores it. So offer the link and watch the log:
# either a running launcher took it, or this copy became the launcher, in
# which case wait for it to finish starting and offer the link again.
start=\$(stat -c %s "\$LOG" 2>/dev/null || echo 0)
"\$WINE" "\$EXE" "\${FLAGS[@]}" "\$@" >>"\$LOG" 2>&1 &
for _ in \$(seq 1 90); do
  sleep 1
  new=\$(tail -c +\$((start + 1)) "\$LOG" 2>/dev/null)
  if grep -q "Another instance is already running" <<<"\$new"; then exit 0; fi
  if grep -q "Application started" <<<"\$new"; then break; fi
done
sleep "\$EXTRA_WAIT"
exec "\$WINE" "\$EXE" "\${FLAGS[@]}" "\$@" >>"\$LOG" 2>&1
EOF
  chmod +x "$WRAPPER"
}

write_desktop() {
  mkdir -p "$DESKTOP_DIR"
  cat >"$DESKTOP_FILE" <<EOF
[Desktop Entry]
# $MARKER.
Type=Application
Name=$APP_NAME
Comment=Habbo Hotel launcher (unofficial Linux setup, runs via Wine)
Exec="$WRAPPER" %u
Icon=$ICON_VALUE
Terminal=false
Categories=Game;
MimeType=x-scheme-handler/$SCHEME;
StartupWMClass=habbo launcher.exe
EOF

  if have update-desktop-database; then
    update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
  fi
  if have xdg-mime; then
    xdg-mime default "$APP_ID.desktop" "x-scheme-handler/$SCHEME" 2>/dev/null \
      || warn "Couldn't register the $SCHEME:// link handler; the website button may not open the app."
  else
    warn "xdg-mime not found; the website's 'Launch and log in' button may not open the app."
  fi
  refresh_menus
}

refresh_menus() {
  local k
  for k in kbuildsycoca6 kbuildsycoca5; do
    if have "$k"; then "$k" >/dev/null 2>&1 || true; break; fi
  done
}

uninstall() {
  info "Removing Habbo Launcher..."
  if [[ -d "$PREFIX_DIR" ]]; then
    if [[ "$PREFIX_DIR" != "$HOME"/* || ! -f "$PREFIX_DIR/system.reg" ]]; then
      die "Refusing to delete $PREFIX_DIR (it doesn't look like a Wine prefix inside your home folder)."
    fi
    if have "$WINESERVER"; then WINEPREFIX="$PREFIX_DIR" "$WINESERVER" -k 2>/dev/null || true; fi
    rm -rf "$PREFIX_DIR"
    rmdir "$APP_DIR" 2>/dev/null || true
  fi
  local f
  for f in "$WRAPPER" "$DESKTOP_FILE"; do
    if [[ -f "$f" ]] && grep -q "$MARKER" "$f"; then rm -f "$f"; fi
  done
  rm -f "$ICON_FILE" "$LOG_FILE"
  local mimeapps="${XDG_CONFIG_HOME:-$HOME/.config}/mimeapps.list"
  if [[ -f "$mimeapps" ]]; then
    sed -i "/^x-scheme-handler\/[^=]*=$APP_ID\.desktop;\{0,1\}\$/d" "$mimeapps" || true
  fi
  if have update-desktop-database; then
    update-desktop-database "$DESKTOP_DIR" >/dev/null 2>&1 || true
  fi
  refresh_menus
  ok "Habbo Launcher has been removed."
}

# -------------------------------------------------------------------- main ---

while [[ $# -gt 0 ]]; do
  case "$1" in
    --installer)      [[ $# -ge 2 ]] || die "--installer needs a file path"; LOCAL_INSTALLER="$2"; shift 2 ;;
    --installer=*)    LOCAL_INSTALLER="${1#*=}"; shift ;;
    --no-gpu)         NO_GPU=1; shift ;;
    --dxvk)           WANT_DXVK=1; shift ;;
    --force-old-wine) FORCE_OLD_WINE=1; shift ;;
    --uninstall)      DO_UNINSTALL=1; shift ;;
    -h|--help)        usage; exit 0 ;;
    *)                die "Unknown option: $1 (see --help)" ;;
  esac
done

if (( DO_UNINSTALL )); then
  uninstall
  exit 0
fi

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

echo "${C_INFO}Habbo Launcher for Linux${C_OFF} — unofficial installer (not affiliated with Sulake)"
echo

check_system
check_wine
make_prefix

EXE="$(find_exe)"
if [[ -n "$EXE" && -z "$LOCAL_INSTALLER" ]]; then
  info "Habbo Launcher is already installed; refreshing the menu entry and settings."
else
  get_installer
  run_installer
fi

install_dxvk
detect_scheme
extract_icon
write_wrapper
write_desktop

echo
ok "All done!"
echo "   • Open \"$APP_NAME\" from your app menu."
echo "   • On habbo.com, \"Launch and log in\" will now open it ($SCHEME:// links)."
echo "   • If it won't start, check the log: $LOG_FILE"
(( NO_GPU )) || echo "   • If it crashes on start, re-run this script with --no-gpu."
if [[ ":$PATH:" != *":$BIN_DIR:"* ]]; then
  echo "   • To start it from a terminal, run: $WRAPPER"
fi
echo
echo "$HELP_TEXT"
